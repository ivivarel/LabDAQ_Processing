void generate(int nTrk=10){
if(!(nTrk<100)){cout <<"too many tracks requested, exit "<< endl; return;}

//booking some histos

//for acceptance
TH1F *hNHits=new TH1F("hNHits", "Number of hits, generated track ", 20,-0.5,19.5);
TH2F *hHits=new TH2F("hHits", " Hits map ", 1500,0,150,2000,-100,100);
TH1F *hBDen=new TH1F("hBDen", " B parameter, all gen tracks", 100,-1.,1.);
TH1F *hBNum=new TH1F("hBNum", " B parameter, tracks having 8 hits", 100,-1.,1.);
hBNum->Sumw2();
hBDen->Sumw2();

// for seeding
TH1F *hFit=new TH1F("hFit", " Seed Fit quality", 1000,0,100);
TH1F *hProb = new TH1F("hProb","Prob fit", 1000,0,1);
TH1F *hFitGood=new TH1F("hFitGood", " Good Seed Fit quality", 1000,0,100);

const Int_t nEvt=100; //generate nEvt events
Double_t maxChi=100.; // cut on track reconstruction quality

//Detector dimensions
//x range goes from 0 to 1.5 m. Planes (10) start at 20 cm, 10 cms apart [20 cm,..,110 cm]
//They are 1m along y. Full detector acceptance for straight tracks coming from the vertex 
//is about +/- 25 degrees in angle

const Int_t nPlanes=10;
const Double_t HalfPlaneWidth =50;  // cm
Double_t xPlanes[nPlanes]; //planes x position
for(Int_t i=0;i<nPlanes;i++)xPlanes[i]=20.+i*10;//in cm

 // start loop over events
 
std::vector<hit> Hits[nPlanes]; //Matrix of Hits: 
std::vector<trueTrack> genTrack; // vector of the generated true tracks

for (Int_t ievt=0;ievt<nEvt;ievt++){
  unsigned int nHits=0; // total hits per event
  unsigned int nHitsP[nPlanes]; //number of hits per plane
  genTrack.clear();
  for (unsigned int iPlanes = 0; iPlanes < nPlanes; ++iPlanes) {
    Hits[iPlanes].clear();
    nHitsP[iPlanes] = 0;
  }
//_____________________________________________
//
//The true track and detector hits generation
//_____________________________________________
// 
// 

  for (Int_t iTrk=0; iTrk<nTrk; iTrk++){

//_____________________________________________
//
// Add code for track generation  Here
//_____________________________________________
// 

    double A = gRandom->Uniform(-2.,2);
    double B = gRandom->Uniform(-0.3,0.3);

//now loop on the planes  to count how many hits in the det

    double xImpact, yImpact;

    for(Int_t i=0;i<nPlanes;i++){

//_____________________________________________
//
// Add code for producing the hits generated by the tracks generated above here  Here
//_____________________________________________
//

      xImpact = xPlanes[i]; 
      yImpact = 0; // This will have to become yImpact = A = B * xImpact, for suitable values of A and B 
      if (TMath::Abs(yImpact)<HalfPlaneWidth){ // check whether the hit is on the detector
	hit l_hit(xImpact,yImpact,iTrk); // create a hit
	Hits[i].push_back(l_hit);  
      }  
    } // close loop on planes
  } // close loop on generated tracks
 } // close loop on events 
  
 TH1F *hAcc=new TH1F(*hBDen);
  //hAcc->SetTitle("Acceptance vs B, at least 8 hits");
  //hAcc->Divide(hBNum,hBDen,1,1,"B");

 TCanvas *cPlot1= new TCanvas();
 cPlot1->Divide(2,2);
 cPlot1->cd(1);
 hNHits->Draw();
 cPlot1->cd(2);
 hHits->Draw("COLZ");
 cPlot1->cd(3);
 hAcc->Draw();
 
 TCanvas *cFit = new TCanvas();
 cFit->Divide(2,2);
 cFit->cd(1);
 hFit->Draw();
 cFit->cd(2);
 hProb->Draw();
 cFit->cd(3);
 hFitGood->Draw();
    

return;
}


